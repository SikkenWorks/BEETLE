#!/usr/bin/env python3
"""Regenerate the FM1 two-frame splash from the supplied exact 240x240 GIF.

Base spans are shared; pink spans are overlay-specific. No resizing,
color re-painting, antialiasing, or invented frames. LCD RGB565 is intrinsic.
"""
from collections import Counter
from pathlib import Path
from PIL import Image
p=Path(__file__).resolve().parents[1]
gif=Image.open(p/'assets/loading-screen/LoadingScreen.gif')
assert gif.size==(240,240) and gif.n_frames==2
assert [gif.seek(i) or gif.info['duration'] for i in range(2)]==[100,100]
frames=[]
for i in range(2):
    gif.seek(i);frames.append(gif.convert('RGB').copy())
def rgb565(c):return (c[0]>>3)<<11|(c[1]>>2)<<5|(c[2]>>3)
raw=[[rgb565(im.getpixel((x,y))) for y in range(240) for x in range(240)] for im in frames]
pink=rgb565((255,0,240))
assert all(raw[0][i]==raw[1][i] for i in range(240*240) if raw[0][i]!=pink and raw[1][i]!=pink)
base=[raw[0][i] if raw[0][i]!=pink else raw[1][i] if raw[1][i]!=pink else 0 for i in range(240*240)]
assert all(v!=pink for v in base)
# For pixels where an insect overlaps a tree, use the untouched reference
# background supplied by the user. Its 9 minor color shifts relative to
# the GIF are restored from the GIF's visible nonpink pixels.
background=Image.open(p/'assets/loading-screen/LoadingScreen-background.png').convert('RGB')
for i in range(240*240):
 if raw[0][i]==pink and raw[1][i]==pink:
  base[i]=rgb565(background.getpixel((i%240,i//240)))
# Some underneath-background differences cannot be inferred from the GIF,
# but the pink sprite always occludes them. Validate exact visible output.
for f in raw:
 assert all((pink if q==pink else b)==q for q,b in zip(f,base))
colors=sorted(set(base)-{0})
assert len(colors)<256
palette={value:idx for idx,value in enumerate(colors)}
def runs(data,oncolor=False):
 out=[]
 for y in range(240):
  x=0
  while x<240:
   v=data[y*240+x]
   if v==0 or (oncolor and v!=pink):x+=1;continue
   e=x+1
   while e<240 and data[y*240+e]==v:e+=1
   if oncolor:out.append((x,y,e-x))
   else:out.append((x,y,e-x,palette[v]))
   x=e
 return out
base_runs=runs(base)
pink_runs=[runs([c if c==pink else 0 for c in frame],True) for frame in raw]
assert all(len(rs)<65536 for rs in [base_runs,*pink_runs])
header=p/'firmware/fm1-native/beetle_boot_frames.h'
header.write_text('''/* SPDX-License-Identifier: GPL-3.0-only
 * AUTO GENERATED by tools/generate_beetle_boot.py from the six original user
 * splash assets. Two 240x240 frames @ 100ms (10 FPS). No interpolation.
 * Uses the LCD's RGB565; coordinates and pixel shapes are exact.
 * DO NOT manually edit this generated file.
 */
#pragma once
#include <stdint.h>
struct beetle_boot_base_run {uint8_t x,y,w,color;};
struct beetle_boot_pink_run {uint8_t x,y,w;};
static const uint16_t beetle_boot_colors[] = {
'''+''.join(' '+','.join('0x%04Xu'%c for c in colors[i:i+12])+',\n' for i in range(0,len(colors),12))+'''};
static const struct beetle_boot_base_run beetle_boot_tree[] = {
'''+''.join(' '+','.join('{%d,%d,%d,%d}'%r for r in base_runs[i:i+8])+',\n' for i in range(0,len(base_runs),8))+'''};
'''+''.join('static const struct beetle_boot_pink_run beetle_boot_bug%d[] = {\n'%i+''.join(' '+','.join('{%d,%d,%d}'%r for r in rs[j:j+12])+',\n' for j in range(0,len(rs),12))+'};\n' for i,rs in enumerate(pink_runs))+'''
#define BEETLE_BOOT_TREE_RUNS (sizeof(beetle_boot_tree)/sizeof(beetle_boot_tree[0]))
#define BEETLE_BOOT_BUG0_RUNS (sizeof(beetle_boot_bug0)/sizeof(beetle_boot_bug0[0]))
#define BEETLE_BOOT_BUG1_RUNS (sizeof(beetle_boot_bug1)/sizeof(beetle_boot_bug1[0]))
''')
print(f'Generated {header}: {len(colors)} colors, {len(base_runs)} tree runs, {len(pink_runs[0])}/{len(pink_runs[1])} beetle runs, approx {2*len(colors)+4*len(base_runs)+3*sum(map(len,pink_runs))} bytes')
