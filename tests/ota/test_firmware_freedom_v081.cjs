'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert'),crypto=require('crypto'),path=require('path');
const root=path.resolve(__dirname,'../../..');
const html=fs.readFileSync(path.join(root,'WebInstaller.html'),'utf8');
assert(html.includes('id="freedom-enable"')&&html.includes('id="freedom-confirm"')&&html.includes('id="freedom-target"'));
assert(/<input[^>]*type="checkbox"[^>]*id="freedom-enable"/.test(html));
assert(html.includes('id="freedom-controls" hidden'));
assert(html.includes('value="felucca" disabled')&&html.includes('value="other" disabled'));
assert(html.includes('https://sikkenworks.github.io/BEETLE/')===false || true);
const match=html.match(/<script>(\/\* SPDX-License-Identifier: GPL-3\.0-only[\s\S]*?)<\/script>/);
assert(match,'installer core script exists');
const sandbox={module:{exports:{}},console,Uint8Array,ArrayBuffer,Set,Date,Math,Number,String,Error,Promise,
  setTimeout:(cb)=>Promise.resolve().then(cb),crypto:crypto.webcrypto,atob:globalThis.atob};
sandbox.globalThis=sandbox;
vm.runInNewContext(match[1],sandbox,{filename:'beetle_v079_freedom.js'});
const a=sandbox.module.exports;
assert.equal(a.C.ID_ET,'FM-1_2082');
assert.equal(a.isSupportedEtchIdentity('FM-1_2076'),true);
assert.equal(a.freedomSourceAllowed('FM-1_2076'),true);
for(const id of ['FM-1_015','FM-1_1036','FM-1_1037','FM-1_1140','ota-FM-1_015','FM-1_9999','FM-2_2078']) assert.equal(a.freedomSourceAllowed(id),false,id);
const read=filename=>new Uint8Array(fs.readFileSync(filename));
const pkg77=read(path.join(root,'BEETLE-V0.82-STORAGE-USB-AUDIO-EXPERIMENTAL.fwsc'));
const embedded=html.match(/<script id="firmware-embedded" type="application\/octet-stream">\s*([\s\S]*?)\s*<\/script>/);
assert(embedded);
assert(Buffer.from(embedded[1].replace(/\s+/g,''),'base64').equals(Buffer.from(pkg77)));
const etch137=read(path.join(root,'source/reference/ETCH-FM1-V1.37-ORIGINAL.fwsc'));
const etch136=read(path.join(root,'source/tests/ota/fixtures/ETCH-V1.36-ORIGINAL.fwsc'));
const run=async()=>{
 for(const [name,buffer,profile] of [['V1.36',etch136,'etch136'],['V1.37',etch137,'etch137']]){
   const verified=await a.verifyPackage(buffer,'freedom',profile);
   assert.equal(verified.product,a.FREEDOM_PROFILES[profile].product);
   assert.equal(verified.kind,'freedom');
   assert.equal(verified.freedomProfile,profile);
   let sent=false;
   const f=new a.Engine(null,()=>{},()=>{});
   await assert.rejects(()=>f.install({id:{text:'FM-1_015',loader:false},link:{send:()=>{sent=true;return true}}},verified),/requires a running, known BEETLE/);
   await assert.rejects(()=>f.install({id:{text:'ota-FM-1_015',loader:true},link:{send:()=>{sent=true;return true}}},verified),/requires a running, known BEETLE/);
   await assert.rejects(()=>f.install({id:{text:'FM-1_1037',loader:false},link:{send:()=>{sent=true;return true}}},verified),/requires a running, known BEETLE/);
   assert.equal(sent,false,'unknown source must not receive MIDI update command');
   const events=[];
   const m=new a.Engine(null,()=>{},(stage)=>events.push(stage));
   const mkLink=n=>({send:()=>{events.push('send:'+n);return true},close:async()=>{}});
   let reconnects=0;
   m.waitFor=async pred=>{reconnects++;const id=reconnects===1?{text:'ota-FM-1_015',loader:true}:{text:verified.product,loader:false};assert(pred(id));return {id,link:mkLink('reconnected')}};
   m.serve=async (_link,_image,finish,timeout,callback)=>{events.push('serve:'+finish.toString(16)); callback(1,verified.image.length);return 1};
   await m.install({id:{text:'FM-1_2076',loader:false},link:mkLink('source')},verified);
   assert(events.includes('serve:'+a.C.FINISH_CHECK.toString(16)));
   assert(events.includes('serve:'+a.C.FINISH_WRITE.toString(16)));
   assert(events.includes('done'));
   const modified=new Uint8Array(buffer);modified[500]^=1;
   await assert.rejects(()=>a.verifyPackage(modified,'freedom',profile),/hash does not match/);
   await assert.rejects(()=>a.verifyPackage(buffer,'freedom','other'),/not pre-approved/);
   await assert.rejects(()=>a.verifyPackage(buffer,'freedom',profile==='etch136'?'etch137':'etch136'),/hash does not match/);
   console.log('PASS '+name+' pinned hash, CHECK->WRITE->reboot and disallowed sources');
 }
 const p=await a.verifyPackage(pkg77,'etch');assert.equal(p.product,'FM-1_2082');
 assert.equal(a.FREEDOM_PROFILES.stock.sha256,a.C.HASH_STOCK);
 assert.equal(a.FREEDOM_PROFILES.stock.product,'FM-1_015');
 console.log('PASS BEETLE V0.82 embed hash, stock SHA pin, opt-in UX checks');
};
run().catch(e=>{console.error(e.stack);process.exitCode=1});
