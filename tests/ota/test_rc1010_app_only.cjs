'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('node:assert/strict'),crypto=require('crypto');
const root=path.resolve(__dirname,'../..');
const html=fs.readFileSync(path.join(root,'WebInstaller.html'),'utf8');
const match=html.match(/<script>(\/\* SPDX-License-Identifier: GPL-3\.0-only[\s\S]*?)<\/script>/);
assert(match,'web OTA core must exist');
const ctx={module:{exports:{}},Uint8Array,ArrayBuffer,Set,Date,Math,Number,String,Error,Promise,console,crypto:crypto.webcrypto,atob:globalThis.atob,setTimeout};
ctx.globalThis=ctx;
vm.runInNewContext(match[1],ctx,{filename:'WebInstaller-rc109.js'});
const api=ctx.module.exports;
const logical=(file)=>new Uint8Array(fs.readFileSync(path.join(root,'tests/ota/generated',file)));
const flash=(name)=>api.verifyFwscLayout(logical(name+'.fwsc')).flash.body;
api.validateFM1AppOnlyFlash(flash('beetle_rc1010'));
api.validateFM1AppOnlyFlash(flash('compatible_foreign_head'));
assert.throws(()=>api.validateFM1AppOnlyFlash(flash('wrong_app_xip')),/XIP/);
assert.throws(()=>api.validateFM1AppOnlyFlash(flash('corrupt_app_payload')),/CRC/);
(async()=>{
 const a=fs.readFileSync(path.join(root,'tests/ota/generated/compatible_foreign_head.fwsc'));
 const b=await api.auditGenericPackage(new Uint8Array(a));
 assert.equal(b.product,'FM-1_2110');
 const damaged=fs.readFileSync(path.join(root,'tests/ota/generated/untrusted_loader.fwsc'));
 await assert.rejects(api.auditGenericPackage(new Uint8Array(damaged)),/different OTA loader|CRC mismatch/i);
 console.log('PASS web JS app-only compatibility, damaged app, wrong XIP, untrusted loader');
})().catch(e=>{console.error(e);process.exitCode=1});
