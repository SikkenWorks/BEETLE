// V21 encoder round-trip and referential correctness, including all 8 patches.
const round=m.BeetleNative.decode(re);
assert.strictEqual(round.patterns[0].channels[4][1].inst,7);
assert.strictEqual(round.instruments[7].type,9);
// Existing V20 content migrates unchanged; V21 stores two supplemental FX slots.
const step=p20.patterns[0].channels[4][1];
