const m=vm.runInContext(code,sandbox);
const old=Uint8Array.from(fs.readFileSync(process.argv[2]));
const recent=Uint8Array.from(fs.readFileSync(process.argv[3]));
const p19=m.BeetleNative.decode(old);
assert(p19.instruments.length===8);
assert(p19.instruments[4].type===2);
